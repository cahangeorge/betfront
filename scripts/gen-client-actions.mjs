#!/usr/bin/env node
/**
 * Generate src/lib/client-actions/{module}.ts — for each server function,
 * exports a same-named async wrapper that calls actions[module][fn](input)
 * and unwraps `{ data, error }`. Lets ported React components keep their
 * `import { foo } from '#/server/foo'` style imports; we only sed the
 * source path to '#/lib/client-actions/foo'.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const FILES = ['datasets', 'tickets', 'predictions', 'scraper', 'penaltyblog', 'soccerdata', 'account', 'jobs'];
const SKIP = new Set([
  'resolveSoccerdataHistoricalMatches',
  'mapFrontbetHistoricalMatches',
  'pickOneX2Odds',
  'sortHistoricalMatches',
  'toNumber',
  'toStringValue',
  'buildSeasonVariants',
  'normalizeSoccerdataScheduleRows',
  'selectRecentMatches',
]);

mkdirSync('src/lib/client-actions', { recursive: true });

let total = 0;
for (const f of FILES) {
  const src = readFileSync(`src/server/${f}.ts`, 'utf8');
  const fns = [...src.matchAll(/^export async function (\w+)\((.*?)\)/gm)]
    .map((m) => ({ name: m[1], hasInput: !!m[2].trim() }))
    .filter((fn) => !SKIP.has(fn.name));

  let out = `// AUTO-GENERATED by scripts/gen-client-actions.mjs — do not edit by hand.\n`;
  out += `// Client-side wrappers for src/server/${f}.ts. Each fn calls the\n`;
  out += `// matching Astro Action over fetch and unwraps { data, error }.\n`;
  out += `// Re-export types from the server module (TS erases these — no runtime\n`;
  out += `// import of server code happens in the browser).\n`;
  out += `export type * from '#/server/${f}';\n`;
  out += `import type * as Server from '#/server/${f}';\n`;
  out += `import { actions } from 'astro:actions';\n\n`;
  out += `async function call(name: string, input: unknown): Promise<unknown> {\n`;
  out += `  const fn = (actions as any).${f}?.[name];\n`;
  out += `  if (!fn) throw new Error(\`Missing action ${f}.\${name}\`);\n`;
  out += `  const { data, error } = await fn(input);\n`;
  out += `  if (error) throw error;\n`;
  out += `  return data;\n`;
  out += `}\n\n`;

  for (const fn of fns) {
    if (fn.hasInput) {
      out += `export async function ${fn.name}(\n`;
      out += `  input?: Parameters<typeof Server.${fn.name}>[0],\n`;
      out += `): Promise<Awaited<ReturnType<typeof Server.${fn.name}>>> {\n`;
      out += `  return (await call('${fn.name}', input)) as Awaited<ReturnType<typeof Server.${fn.name}>>;\n`;
      out += `}\n\n`;
    } else {
      out += `export async function ${fn.name}(): Promise<Awaited<ReturnType<typeof Server.${fn.name}>>> {\n`;
      out += `  return (await call('${fn.name}', undefined)) as Awaited<ReturnType<typeof Server.${fn.name}>>;\n`;
      out += `}\n\n`;
    }
  }

  writeFileSync(`src/lib/client-actions/${f}.ts`, out, 'utf8');
  total += fns.length;
}

console.log(`✓ Generated client-actions for ${FILES.length} modules, ${total} fns.`);
